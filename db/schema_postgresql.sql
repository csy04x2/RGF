-- RGF v0.1 PostgreSQL schema; preserves existing MySQL db/schema.sql.
CREATE TABLE IF NOT EXISTS source_documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(500) NOT NULL,
 source_type VARCHAR(8) NOT NULL CHECK (source_type IN ('PDF','TEXT')),
 organization VARCHAR(255), published_at TIMESTAMP, source_url TEXT,
 file_path TEXT, raw_text TEXT, metadata_json JSONB,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS analysis_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_document_id BIGINT NOT NULL REFERENCES source_documents(id) ON DELETE CASCADE,
 model_name VARCHAR(100) NOT NULL, prompt_version VARCHAR(50) NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
 structured_source_json JSONB, analysis_json JSONB, error_message TEXT,
 started_at TIMESTAMP, completed_at TIMESTAMP, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_run_document ON analysis_runs(source_document_id);
CREATE TABLE IF NOT EXISTS article_ideas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 analysis_run_id BIGINT NOT NULL REFERENCES analysis_runs(id) ON DELETE CASCADE,
 lead_id VARCHAR(50), title VARCHAR(500) NOT NULL, angle TEXT NOT NULL,
 why_it_matters TEXT NOT NULL, reporting_questions JSONB NOT NULL,
 evidence_needed JSONB NOT NULL, reporting_targets JSONB,
 priority VARCHAR(8) NOT NULL CHECK (priority IN ('HIGH','MEDIUM','LOW')),
 review_status VARCHAR(10) NOT NULL DEFAULT '검토대기' CHECK (review_status IN ('검토대기','승인','보류')),
 review_note TEXT, reviewer VARCHAR(255), reviewed_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_article_ideas_run_lead UNIQUE (analysis_run_id,lead_id)
);
CREATE INDEX IF NOT EXISTS idx_idea_run ON article_ideas(analysis_run_id);
CREATE TABLE IF NOT EXISTS source_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_document_id BIGINT NOT NULL REFERENCES source_documents(id) ON DELETE CASCADE,
 evidence_type VARCHAR(12) NOT NULL CHECK (evidence_type IN ('PAGE_TEXT','PARAGRAPH','TABLE')),
 location_label VARCHAR(255), content TEXT NOT NULL,
 structured_data JSONB, content_hash CHAR(64),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_source_evidence_identity UNIQUE (source_document_id,location_label,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_evidence_document ON source_evidence(source_document_id);
CREATE TABLE IF NOT EXISTS article_evidence (
 article_idea_id BIGINT NOT NULL REFERENCES article_ideas(id) ON DELETE CASCADE,
 source_evidence_id BIGINT NOT NULL REFERENCES source_evidence(id) ON DELETE CASCADE,
 relation_type VARCHAR(12) NOT NULL CHECK (relation_type IN ('SUPPORTS','CONTEXT','GAP_TRIGGER')),
 explanation TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (article_idea_id,source_evidence_id)
);
